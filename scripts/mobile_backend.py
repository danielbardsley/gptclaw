"""Explicit public development bindings; never starts a backend or reads secrets."""
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

import private_apps as app
import project_dependencies as deps
import project_worktrees as worktrees

CONFIG='.gptclaw/backend.local.json'
GENERATED='src/config/backend.generated.ts'


def url(value, project, hostname):
    """Accept only the selected ingress identity and exact project API prefix."""
    app.need(isinstance(value,str) and len(value)<=512 and re.fullmatch(r'[!-~]+',value),'mobile-policy')
    try: parsed=urlsplit(value);port=parsed.port
    except ValueError:raise app.AppError('mobile-policy') from None
    app.need(parsed.scheme=='https' and parsed.hostname==hostname and port in (None,443)
             and re.fullmatch(r'[a-z0-9][a-z0-9.-]*\.ts\.net',hostname) is not None
             and parsed.netloc==hostname and not parsed.username and not parsed.password
             and not parsed.query and not parsed.fragment
             and parsed.path==f'/projects/{project}/api','mobile-policy')
    return value


def inspect(root, hostname=None):
    """Validate local binding against canonical Python/PostgreSQL source identity."""
    root,document=app.target(root);app.need(document['schema_version']==9,'mobile-unsupported')
    raw=deps.read_bytes(root/CONFIG,8192);value=deps.json_data(raw)
    app.need(isinstance(value,dict) and set(value)=={'schema_version','mobile','backend','root','profile','contract_version','api_url'}
             and type(value['schema_version']) is int and value['schema_version']==1
             and isinstance(value['root'],str) and Path(value['root']).is_absolute()
             and isinstance(value['backend'],str) and re.fullmatch(r'[a-z][a-z0-9]*(?:-[a-z0-9]+)*',value['backend']) is not None
             and len(value['backend'])<=48
             and value['mobile']==document['project']['id'] and value['profile']=='development'
             and type(value['contract_version']) is int and value['contract_version']==1,'mobile-policy')
    backend,contract=app.target(value['root'])
    app.need(contract['schema_version']==8 and contract['project']['id']==value['backend']
             and contract['components']['api']['adapter']=='fastapi-v1','mobile-policy')
    worktrees.canonical(backend)
    url(value['api_url'],value['backend'],hostname or app.node_identity())
    return value


def generated(value):
    """Materialize only public inputs into native source; never forward environment."""
    public={'enabled':True,'profile':value['profile'],'contractVersion':value['contract_version'],'apiUrl':value['api_url']}
    return '// Public development configuration. Generated by gptclawctl backend bind.\nexport const backend = '+json.dumps(public,sort_keys=True)+' as const;\n'


def bind(root, backend_root, api_url):
    """Bind stopped canonical mobile source without modifying backend activation."""
    root,document=app.target(root);app.need(document['schema_version']==9,'mobile-unsupported')
    worktrees.canonical(root)
    backend,contract=app.target(backend_root);app.need(contract['schema_version']==8,'mobile-policy')
    worktrees.canonical(backend)
    value={'schema_version':1,'mobile':document['project']['id'],'backend':contract['project']['id'],
           'root':str(backend),'profile':'development','contract_version':1,
           'api_url':url(api_url,contract['project']['id'],app.node_identity())}
    with app.locked(document['project']['id']):
        import metro_sessions
        metro_sessions.assert_stopped(root,document['project']['id'])
        app.save(app.safe(root/CONFIG),value)
        prepare(root)
    return {'project':document['project']['id'],'backend':value['backend'],'profile':'development','state':'backend-bound'}


def prepare(root):
    """Write checked configuration before a job/session begins, with no URL in output."""
    value=inspect(root);path=app.safe(Path(root)/GENERATED)
    app.need(path.is_file() and path.stat().st_uid==__import__('os').getuid(),'path')
    content=generated(value)
    with path.open('w') as stream:stream.write(content)
    path.chmod(0o600)
    return fingerprint(root)


def fingerprint(root):
    """Include binding and generated public inputs in session freshness checks."""
    value=inspect(root)
    app.need(deps.read_bytes(Path(root)/GENERATED,8192).decode()==generated(value),'mobile-policy')
    return {name:hashlib.sha256(deps.read_bytes(Path(root)/name,8192)).hexdigest() for name in (CONFIG,GENERATED)}
